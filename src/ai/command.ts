import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { slug } from '../util';
import { KEYWORDS, type DocshotLanguage } from '../sources/rst';
import type { AnalyzeJob, AnalyzeResult } from './analyze';
import { aiConfig, aiConfigProblems, loadEnv } from './client';
import { findImageReferences, idExists, insertBlock } from './insert';

export const FROM_IMAGE_HELP = `docshots from-image [Bild] [Optionen]

Erzeugt Screenshot-Schritte aus einem alten Doku-Bild: meldet sich an, öffnet die URL,
lässt ein Vision-Modell (OpenAI-kompatible API, Konfiguration in .env) Schritte vorschlagen,
probiert sie im Browser aus und korrigiert sie bei Fehlern.

  --url <url>         Seite, auf der das Bild heute entsteht (relativ zur baseURL). Wird abgefragt, wenn sie fehlt.
  --persona <name>    Anmelden als Persona (wird abgefragt; leer = ohne Anmeldung)
  --id <id>           Screenshot-ID (Standard: Dateiname des Bildes)
  --lang de|en        Sprache der Schritte und der Oberfläche (Standard: de)
  --viewport <name>   Viewport aus der Konfiguration (Standard: desktop)
  --attempts <n>      Korrekturrunden (Standard: 3)
  --insert            Block direkt in die RST-Datei einfügen, die das Bild verwendet, und Bildpfad umstellen
  --docs <glob>       RST-Dateien für --insert (Standard: Documentation/**/*.rst)
  --yes               nichts abfragen (für CI)

.env:
  DOCSHOTS_AI_BASE_URL=https://api.openai.com/v1
  DOCSHOTS_AI_API_KEY=sk-…
  DOCSHOTS_AI_MODEL=gpt-4o
`;

interface Helpers {
  binOf(pkg: string, bin: string): string;
  run(script: string, args: string[], workDir: string): Promise<{ code: number; output: string }>;
  projectSteps(config: string): Promise<string[]>;
}

interface Options {
  image?: string;
  url?: string;
  persona?: string;
  id?: string;
  lang: DocshotLanguage;
  viewport: string;
  attempts: number;
  insert: boolean;
  docs: string[];
  yes: boolean;
  config: string;
  workDir: string;
}

function parse(argv: string[], config: string, workDir: string): Options {
  const o: Options = { lang: 'de', viewport: 'desktop', attempts: 3, insert: false, docs: ['Documentation/**/*.rst'], yes: false, config, workDir };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => argv[++i];
    if (a === '--url') o.url = next();
    else if (a === '--persona') o.persona = next();
    else if (a === '--id') o.id = next();
    else if (a === '--lang') o.lang = next() as DocshotLanguage;
    else if (a === '--viewport') o.viewport = next();
    else if (a === '--attempts') o.attempts = Math.max(1, Number(next()) || 3);
    else if (a === '--insert') o.insert = true;
    else if (a === '--docs') o.docs = [next()];
    else if (a === '--yes' || a === '-y') o.yes = true;
    else if (!a.startsWith('-') && !o.image) o.image = a;
    else throw new Error(`Unbekannte Option: ${a}\n\n${FROM_IMAGE_HELP}`);
  }
  if (!(o.lang in KEYWORDS)) throw new Error(`--lang muss de oder en sein, nicht "${o.lang}"`);
  return o;
}

async function askMissing(o: Options): Promise<void> {
  const interactive = !o.yes && process.stdin.isTTY && process.stdout.isTTY;
  if (!interactive) {
    if (!o.image || !o.url) throw new Error('Bild und --url sind nötig (ohne Terminal wird nicht nachgefragt).');
    return;
  }
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  try {
    while (!o.image || !fs.existsSync(o.image)) {
      if (o.image) console.log(`  Datei nicht gefunden: ${o.image}`);
      o.image = (await rl.question('Altes Bild (Pfad): ')).trim();
    }
    while (!o.url) {
      o.url = (await rl.question(`Auf welcher URL entsteht "${path.basename(o.image)}" heute? (z. B. /administration/persons): `)).trim();
    }
    if (o.persona === undefined) {
      o.persona = (await rl.question('Anmelden als Persona (leer = ohne Anmeldung): ')).trim() || undefined;
    }
  } finally {
    rl.close();
  }
}

function featureFor(job: AnalyzeJob, jobFile: string, viewport: string): string {
  const kw = KEYWORDS[job.lang];
  return [
    `# language: ${job.lang}`,
    '# GENERATED by "docshots from-image" – temporary',
    `${kw.feature}: docshots from-image`,
    '',
    `  @docshot-analyze @lang:${job.lang} @viewports:${viewport} @schemes:light`,
    `  ${kw.scenario}: _analyze-${job.id}`,
    `    * docshots-analyze "${jobFile.split(path.sep).join('/')}"`,
    '',
  ].join('\n');
}

export async function fromImage(argv: string[], config: string, workDirArg: string, h: Helpers): Promise<number> {
  if (argv.includes('--help') || argv.includes('-h')) {
    process.stdout.write(FROM_IMAGE_HELP);
    return 0;
  }
  const rootDir = process.cwd();
  loadEnv(rootDir);
  const ai = aiConfig();
  const problems = aiConfigProblems(ai);
  if (problems.length) {
    console.error(problems.join('\n'));
    return 1;
  }

  const o = parse(argv, config, workDirArg);
  await askMissing(o);
  const image = path.resolve(o.image!);
  if (!fs.existsSync(image)) throw new Error(`Bild nicht gefunden: ${image}`);

  const id = slug(o.id ?? path.basename(image, path.extname(image)));
  const existing = idExists(rootDir, [...o.docs, 'Documentation/**/*.feature'], id);
  if (existing) throw new Error(`Die Screenshot-ID "${id}" gibt es schon in ${existing} – bitte --id angeben.`);

  const workDir = path.resolve(o.workDir);
  const analyzeDir = path.join(workDir, 'analyze');
  fs.rmSync(path.join(analyzeDir, id), { recursive: true, force: true });
  fs.mkdirSync(path.join(analyzeDir, id), { recursive: true });

  console.log(`→ Analysiere ${path.relative(rootDir, image)} gegen ${o.url}${o.persona ? ` als "${o.persona}"` : ''} mit ${ai.model} …`);

  const job: AnalyzeJob = {
    id,
    image,
    url: o.url!,
    persona: o.persona,
    lang: o.lang,
    attempts: o.attempts,
    workDir: analyzeDir,
    projectSteps: await h.projectSteps(o.config),
  };
  const jobFile = path.join(analyzeDir, id, 'job.json');
  fs.writeFileSync(jobFile, JSON.stringify(job, null, 2));
  const featureFile = path.join(analyzeDir, `${id}.feature`);
  fs.writeFileSync(featureFile, featureFor(job, jobFile, o.viewport));

  process.env.DOCSHOTS_ANALYZE = '1';
  try {
    const gen = await h.run(h.binOf('playwright-bdd', 'bddgen'), ['-c', o.config], o.workDir);
    if (gen.code !== 0) return gen.code;
    const project = `${o.viewport}-light-${o.lang}`;
    const pw = await h.run(
      h.binOf('@playwright/test', 'playwright'),
      ['test', '-c', o.config, '--project', project, '--grep', `_analyze-${id}`, '--workers', '1', '--reporter', 'line'],
      o.workDir,
    );
    const resultFile = path.join(analyzeDir, id, 'result.json');
    if (!fs.existsSync(resultFile)) {
      console.error(pw.code !== 0 ? 'Analyse fehlgeschlagen (siehe Ausgabe oben).' : 'Kein Ergebnis gefunden.');
      return pw.code || 1;
    }
    return report(JSON.parse(fs.readFileSync(resultFile, 'utf8')) as AnalyzeResult, o, rootDir, analyzeDir);
  } finally {
    fs.rmSync(featureFile, { force: true });
    // the generated spec must not end up in normal runs
    fs.rmSync(path.join(workDir, 'bdd-gen', path.relative(rootDir, analyzeDir)), { recursive: true, force: true });
  }
}

function report(result: AnalyzeResult, o: Options, rootDir: string, analyzeDir: string): number {
  const rel = (p: string) => path.relative(rootDir, p).split(path.sep).join('/');
  const block = [`..  docshot: ${result.id}`, ...result.steps.map((s) => `    ${s}`)].join('\n');
  fs.writeFileSync(path.join(analyzeDir, result.id, 'docshot.rst'), block + '\n');

  console.log('');
  if (result.error && !result.steps.length) {
    console.error(`✘ ${result.error}`);
    return 1;
  }
  console.log(result.ok ? `✔ Schritte funktionieren (Versuch ${result.attempts.length}/${o.attempts}):` : `⚠ Schritte noch fehlerhaft nach ${result.attempts.length} Versuchen – bitte von Hand prüfen:`);
  console.log('');
  console.log(block);
  console.log('');
  if (!result.ok) {
    for (const e of result.attempts.at(-1)?.errors ?? []) console.log(`  ✘ ${e}`);
    console.log('');
  }
  for (const n of result.notes) console.log(`  • ${n}`);
  if (result.notes.length) console.log('');
  console.log(`Vergleich:  alt   ${rel(path.resolve(o.image!))}`);
  if (result.preview) console.log(`            neu   ${rel(result.preview)}`);
  console.log(`Block:      ${rel(path.join(analyzeDir, result.id, 'docshot.rst'))}`);

  if (o.insert) {
    if (!result.ok) {
      console.log('\n--insert übersprungen, weil die Schritte nicht funktionieren.');
      return 2;
    }
    const refs = findImageReferences(rootDir, o.docs, path.resolve(o.image!));
    if (!refs.length) {
      console.log('\n--insert: keine RST-Datei verwendet dieses Bild – Block bitte von Hand einfügen.');
      return 0;
    }
    const byFile = new Map(refs.map((r) => [r.file, r]));
    const [first] = byFile.values();
    const newPath = insertBlock(first, result.id, result.steps, result.plannedFile, rootDir);
    console.log(`\nEingefügt in ${rel(first.file)}:${first.line + 1}, Bildpfad → ${newPath}`);
    if (byFile.size > 1) {
      console.log(`Das Bild wird auch verwendet in: ${[...byFile.keys()].slice(1).map(rel).join(', ')} – dort Pfad auf ${newPath} umstellen.`);
    }
    console.log('Danach: npx docshots test --grep ' + result.id);
  }
  return result.ok ? 0 : 2;
}
