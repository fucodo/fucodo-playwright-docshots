/**
 * Extracts embedded docshot blocks from reStructuredText files.
 *
 * A block is an RST *comment* (no `::`), so the TYPO3 renderer ignores it:
 *
 *   ..  docshot: user-create
 *       @viewports:desktop,mobile @lang:de
 *       Angenommen ich bin angemeldet als "schooladmin"
 *       Wenn ich auf den Button "Neuer Benutzer" klicke
 *       Dann erstelle einen Screenshot
 *
 * Optional, anywhere in the file, to override the language of all blocks:
 *
 *   ..  docshot-language: en
 */

export type DocshotLanguage = 'de' | 'en';

export interface RstBlock {
  id: string;
  /** 1-based line of the `.. docshot:` marker */
  line: number;
  tags: string[];
  steps: { text: string; line: number }[];
}

export interface ParsedRstFile {
  file: string;
  language?: DocshotLanguage;
  blocks: RstBlock[];
}

export class DocshotSourceError extends Error {
  constructor(public readonly file: string, public readonly line: number, message: string) {
    super(`${file}:${line}: ${message}`);
    this.name = 'DocshotSourceError';
  }
}

const BLOCK_START = /^(\s*)\.\.\s+docshot:\s*(\S+)\s*$/;
const LANGUAGE_MARKER = /^\s*\.\.\s+docshot-language:\s*(\S+)\s*$/;
const VALID_ID = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

export const KEYWORDS: Record<DocshotLanguage, { feature: string; scenario: string; steps: string[] }> = {
  de: {
    feature: 'Funktionalität',
    scenario: 'Szenario',
    steps: ['Angenommen', 'Gegeben sei', 'Gegeben seien', 'Wenn', 'Dann', 'Und', 'Aber', '*'],
  },
  en: {
    feature: 'Feature',
    scenario: 'Scenario',
    steps: ['Given', 'When', 'Then', 'And', 'But', '*'],
  },
};

function indentOf(line: string): number {
  return line.length - line.trimStart().length;
}

export function parseRst(file: string, content: string): ParsedRstFile {
  const lines = content.split(/\r?\n/);
  const result: ParsedRstFile = { file, blocks: [] };

  for (let i = 0; i < lines.length; i++) {
    const lang = LANGUAGE_MARKER.exec(lines[i]);
    if (lang) {
      const value = lang[1] as DocshotLanguage;
      if (!(value in KEYWORDS)) {
        throw new DocshotSourceError(file, i + 1, `Unbekannte Sprache "${lang[1]}" (erlaubt: ${Object.keys(KEYWORDS).join(', ')})`);
      }
      result.language = value;
      continue;
    }

    const start = BLOCK_START.exec(lines[i]);
    if (!start) continue;

    const baseIndent = start[1].length;
    const id = start[2];
    if (!VALID_ID.test(id)) {
      throw new DocshotSourceError(file, i + 1, `Ungültige Screenshot-ID "${id}" – erlaubt sind Buchstaben, Ziffern, ".", "_" und "-".`);
    }

    const block: RstBlock = { id, line: i + 1, tags: [], steps: [] };
    let j = i + 1;
    for (; j < lines.length; j++) {
      const line = lines[j];
      if (line.trim() === '') continue;
      if (indentOf(line) <= baseIndent) break; // block ends at first line not indented deeper
      const text = line.trim();
      if (text.startsWith('#')) continue; // comments inside the block
      if (text.startsWith('@')) {
        if (block.steps.length > 0) {
          throw new DocshotSourceError(file, j + 1, 'Tags (@…) müssen vor dem ersten Schritt stehen.');
        }
        block.tags.push(...text.split(/\s+/).filter(Boolean));
        continue;
      }
      block.steps.push({ text, line: j + 1 });
    }

    if (block.steps.length === 0) {
      throw new DocshotSourceError(file, i + 1, `Der Screenshot-Block "${id}" enthält keine Schritte.`);
    }
    result.blocks.push(block);
    i = j - 1;
  }

  return result;
}

/** Checks that every step starts with a Gherkin keyword of the file's language. */
export function validateSteps(parsed: ParsedRstFile, language: DocshotLanguage): void {
  const keywords = KEYWORDS[language].steps;
  for (const block of parsed.blocks) {
    for (const step of block.steps) {
      const ok = keywords.some((k) => step.text === k || step.text.startsWith(k + ' '));
      if (!ok) {
        throw new DocshotSourceError(
          parsed.file,
          step.line,
          `Schritt beginnt nicht mit einem Schlüsselwort (${keywords.filter((k) => k !== '*').join(', ')}): "${step.text}"`,
        );
      }
    }
  }
}

export interface GeneratedFeature {
  content: string;
  /** generated line (1-based) → source line (1-based) */
  lineMap: Record<number, number>;
}

/** Turns all blocks of one RST file into a single .feature file. */
export function toFeature(parsed: ParsedRstFile, language: DocshotLanguage, sourceLabel: string): GeneratedFeature {
  const kw = KEYWORDS[language];
  const out: string[] = [];
  const lineMap: Record<number, number> = {};
  const push = (text: string, sourceLine?: number) => {
    out.push(text);
    if (sourceLine) lineMap[out.length] = sourceLine;
  };

  push(`# language: ${language}`);
  push(`# GENERATED by playwright-docshots from ${sourceLabel} – do not edit, edit the RST file instead.`);
  push(`${kw.feature}: ${sourceLabel}`, 1);
  for (const block of parsed.blocks) {
    push('');
    push(`  # source: ${sourceLabel}:${block.line}`, block.line);
    // German steps only work against the German UI: unless the block says otherwise,
    // it runs only in the language variant of its document.
    const hasLangTag = block.tags.some((t) => /^@(lang|language|languages):/i.test(t));
    const tags = ['@docshot', ...(hasLangTag ? [] : [`@lang:${language}`]), ...block.tags];
    push(`  ${tags.join(' ')}`, block.line);
    push(`  ${kw.scenario}: ${block.id}`, block.line);
    for (const step of block.steps) push(`    ${step.text}`, step.line);
  }
  push('');
  return { content: out.join('\n'), lineMap };
}
